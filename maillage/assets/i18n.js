  const LANGS = { fr: { dir: 'ltr', label: 'Français', short: 'FR' }, ar: { dir: 'rtl', label: 'العربية', short: 'AR' } };
  ML.lang = ML.ls.get('lang', 'fr') === 'ar' ? 'ar' : 'fr';
  // Un montant (« 6 500 DA ») est isolé : sans cela, l'algorithme bidirectionnel le lit « DA 6 500 » dans une phrase en arabe.
  const _price = ML.fmt.price;
  ML.fmt.price = (v) => (ML.lang === 'ar' ? '\u2066' + _price(v) + '\u2069' : _price(v));
  /** Traduit une chaîne française exacte ; renvoie le français si l'arabe n'est pas (encore) traduit. */
  // Messages du serveur qui contiennent une valeur (nom de produit, taille limite) : traduits par motif.
  const PATTERNS = [
    [/^Stock insuffisant pour « (.+) » dans ce point de vente\. Choisissez une quantité plus petite ou un autre magasin\.$/, 'المخزون غير كافٍ من « $1 » في نقطة البيع هذه. اختر كمية أقل أو متجراً آخر.'],
    [/^L'envoi a échoué\. L'image fait peut-être plus de (\d+) Mo\.$/, 'فشل الإرسال. قد تكون الصورة أكبر من $1 ميغابايت.'],
    [/^Image trop lourde \((\d+) Mo maximum\)\.$/, 'الصورة ثقيلة جداً ($1 ميغابايت كحدّ أقصى).'],
  ];
  ML.t = (fr) => {
    if (ML.lang !== 'ar' || typeof fr !== 'string') return fr;
    if (DICT[fr]) return DICT[fr];
    for (const [re, ar] of PATTERNS) { if (re.test(fr)) return fr.replace(re, ar); }
    return fr;
  };
  /** Chiffres de comptage : l'arabe standard garde le nom au singulier après un nombre. */
  ML.fmt.plural = (n, one, many) => {
    if (ML.lang === 'ar') return ML.fmt.num(n) + ' ' + ML.t(one);
    return ML.fmt.num(n) + ' ' + (n > 1 ? (many || one + 's') : one);
  };

  function applyLang() {
    const l = LANGS[ML.lang];
    document.documentElement.lang = ML.lang;
    document.documentElement.dir = l.dir;
    document.documentElement.classList.toggle('is-rtl', ML.lang === 'ar');
  }
  applyLang(); // avant même le premier rendu (évite un flash de mise en page)

  /** Bouton de bascule FR/AR, à poser dans l'en-tête de chaque page (data-act="lang"). */
  ML.langToggle = (cls) => {
    const next = ML.lang === 'ar' ? 'fr' : 'ar';
    return ML.html`<button class="lang-switch ${cls || ''}" type="button" data-act="lang" data-next="${next}" aria-label="${ML.lang === 'ar' ? 'Switch to French' : 'التبديل إلى العربية'}">${LANGS[next].short}</button>`;
  };
  ML.actions.lang = (el) => {
    ML.lang = el.dataset.next === 'ar' ? 'ar' : 'fr';
    ML.ls.set('lang', ML.lang);
    location.reload();
  };

  /** Icônes directionnelles (flèches, chevrons) : à retourner en miroir en RTL. CSS : voir rtl.css. */
  const DIR_ICONS = new Set(['arrow-left', 'arrow-right', 'chevron-left', 'chevron-right', 'navigation', 'log-out', 'external-link', 'arrow-up-right']);
  const rawIcon = ML.icon;
  ML.icon = (name, cls) => rawIcon(name, DIR_ICONS.has(name) ? ((cls || '') + ' ico-dir').trim() : cls);

  /** Jours de la semaine et dates : bascule d'ensemble de libellés. */
  const DAYS_AR = ['الأحد', 'الإثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت'];
  const _DAYS_FR = ML.DAYS.slice();
  Object.defineProperty(ML, 'DAYS', { get: () => (ML.lang === 'ar' ? DAYS_AR : _DAYS_FR) });
  const locale = () => (ML.lang === 'ar' ? 'ar-DZ' : 'fr-FR');
  const _fmt = ML.fmt;
  ['price', 'date', 'day', 'time'].forEach(() => {}); // (les fonctions ci-dessous remplacent directement)
  ML.fmt.date = (ts) => new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'short', year: 'numeric' }).format(new Date(ts * 1000));
  ML.fmt.day = (ts) => new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'short' }).format(new Date(ts * 1000));
  ML.fmt.time = (ts) => new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }).format(new Date(ts * 1000));
  ML.fmt.ago = (ts) => {
    const s = Math.max(0, Date.now() / 1000 - ts);
    if (ML.lang === 'ar') {
      if (s < 90) return 'الآن';
      if (s < 3600) return 'منذ ' + Math.round(s / 60) + ' د';
      if (s < 86400) return 'منذ ' + Math.round(s / 3600) + ' س';
      if (s < 172800) return 'أمس';
      if (s < 7 * 86400) return 'منذ ' + Math.round(s / 86400) + ' ي';
      return ML.fmt.day(ts);
    }
    if (s < 90) return 'à l\'instant';
    if (s < 3600) return 'il y a ' + Math.round(s / 60) + ' min';
    if (s < 86400) return 'il y a ' + Math.round(s / 3600) + ' h';
    if (s < 172800) return 'hier';
    if (s < 7 * 86400) return 'il y a ' + Math.round(s / 86400) + ' j';
    return ML.fmt.day(ts);
  };

  /** Nom d'une zone (wilaya) dans la langue courante — zones.json porte désormais `ar` en plus de `name`. */
  ML.zoneName = (z) => (!z ? '' : (ML.lang === 'ar' && z.ar ? z.ar : z.name));
  /** Zone d'un point de vente : résout son code wilaya dans la langue courante si possible, sinon garde le nom envoyé par le serveur (toujours en français). */
  ML.storeZone = (s) => (s && s.wilaya && ML.zones && ML.zones[s.wilaya] ? ML.zoneName(ML.zones[s.wilaya]) : (s ? s.zone : ''));

  /**
   * Traduit en bloc une page **entièrement statique** (ici, index.html : aucune donnée saisie par
   * une entreprise ou un client n'y apparaît). Remplace chaque nœud de texte et chaque attribut
   * (placeholder, aria-label, title) dont le contenu exact est une clé du dictionnaire. Ne jamais
   * appeler sur une page qui affiche du contenu d'utilisateur (produits, notes, adresses…) : la
   * correspondance se fait sur le texte exact, un nom qui coïnciderait avec une clé serait traduit.
   */
  ML.translateDom = (root) => {
    const skip = (n) => n.nodeType === 1 && /^(SCRIPT|STYLE)$/.test(n.tagName);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: (n) => (skip(n.parentNode) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT) });
    let n;
    while ((n = walker.nextNode())) {
      const raw = n.nodeValue;
      const trimmed = raw.trim();
      if (trimmed && DICT[trimmed]) n.nodeValue = raw.replace(trimmed, ML.t(trimmed));
    }
    root.querySelectorAll('[placeholder],[aria-label],[title]').forEach((el) => {
      ['placeholder', 'aria-label', 'title'].forEach((attr) => {
        const v = el.getAttribute(attr);
        if (v && DICT[v]) el.setAttribute(attr, ML.t(v));
      });
    });
  };
